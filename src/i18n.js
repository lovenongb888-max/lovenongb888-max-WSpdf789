const STRINGS = { th, en }

export const LANGS = [
  { code: 'th', label: 'TH' },
  { code: 'en', label: 'EN' },
]

export function makeTranslator(lang) {
  const dict = STRINGS[lang] || STRINGS.th
  return (key, vars) => {
    let value = dict[key] ?? STRINGS.th[key] ?? key
    if (vars) {
      for (const [name, replacement] of Object.entries(vars)) {
        value = value.replace(new RegExp(`\\{${name}\\}`, 'g'), replacement)
      }
    }
    return value
  }
}
